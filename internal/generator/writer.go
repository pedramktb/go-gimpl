func (g *generator) generatePgMethods(s structInfo) {
	set := s.Impls["pgimpl"]

	if set.IsEntity {
		g.generatePgColumn(s)
		g.generatePgColumns(s)
		g.generateNewWithPgColumnPtrs(s)
	}

	if set.IsCreate {
		g.generateCreatePgColumns(s)
		g.generateCreatePgColumnVals(s)
	}

	if set.IsUpdate {
		g.generateIdentifyPgColumns(s)
		g.generateIdentifyPgColumnVals(s)
		g.generateUpdatePgColumns(s)
		g.generateUpdatePgColumnVals(s)
	}
}

func (g *generator) generatePgColumn(s structInfo) {
	g.printf("func (e %s) PgColumn(field string) string {\n", s.Name)
	g.printf("\tswitch field {\n")
	for _, f := range s.Fields {
		if f.IsDelegate {
			g.printf("\tdefault:\n")
			g.printf("\t\tif strings.HasPrefix(field, \"%s\") {\n", f.Prefix)
			g.printf("\t\t\treturn \"%s\" + e.%s.PgColumn(strings.TrimPrefix(field, \"%s\"))\n", f.Prefix, f.Name, f.Prefix)
			g.printf("\t\t}\n")
			continue
		}

		pgInfo := f.Impls["pgimpl"]
		g.printf("\tcase \"%s\":\n", f.FieldName)
		g.printf("\t\treturn \"%s\"\n", pgInfo.ColumnName)
	}
	g.printf("\t}\n\treturn \"\"\n}\n\n")
}

func (g *generator) generatePgColumns(s structInfo) {
	g.printf("func (e %s) PgColumns() []string {\n", s.Name)
	g.printf("\tcols := []string{\n")
	for _, f := range s.Fields {
		if f.IsDelegate {
			continue
		}
		pgInfo := f.Impls["pgimpl"]
		g.printf("\t\t\"%s\",\n", pgInfo.ColumnName)
	}
	g.printf("\t}\n")

	for _, f := range s.Fields {
		if f.IsDelegate {
			g.printf("\tfor _, c := range e.%s.PgColumns() {\n", f.Name)
			g.printf("\t\tcols = append(cols, \"%s\" + c)\n", f.Prefix)
			g.printf("\t}\n")
		}
	}
	g.printf("\treturn cols\n}\n\n")
}

func (g *generator) generateNewWithPgColumnPtrs(s structInfo) {
	g.printf("func (e %s) NewWithPgColumnPtrs() (any, []any) {\n", s.Name)
	g.printf("\tn := &%s{}\n", s.Name)
	g.printf("\tptrs := []any{\n")
	for _, f := range s.Fields {
		if f.IsDelegate {
			continue
		}
		g.printf("\t\t&n.%s,\n", f.Name)
	}
	g.printf("\t}\n")

	for _, f := range s.Fields {
		if f.IsDelegate {
			g.printf("\t{\n")
			g.printf("\t\tinner, innerPtrs := n.%s.NewWithPgColumnPtrs()\n", f.Name)
			g.printf("\t\tif val, ok := inner.(*%s); ok {\n", f.TypeName)
			g.printf("\t\t\tn.%s = *val\n", f.Name)
			g.printf("\t\t}\n")
			g.printf("\t\tptrs = append(ptrs, innerPtrs...)\n")
			g.printf("\t}\n")
		}
	}
	g.printf("\treturn n, ptrs\n}\n\n")
}

