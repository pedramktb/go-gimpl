package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func generateFile(originalFile, pkgName string, structs []structInfo) error {
	g := &generator{
		buf:     &bytes.Buffer{},
		pkgName: pkgName,
		structs: structs,
	}
	return g.generate(originalFile)
}

type generator struct {
	buf     *bytes.Buffer
	pkgName string
	structs []structInfo
}

func (g *generator) generate(originalFile string) error {
	g.printf("// Code generated by gimpl. DO NOT EDIT.\n")
	g.printf("package %s\n\n", g.pkgName)

	g.generateImports()

	for _, s := range g.structs {
		g.generateCommonMethods(s)

		// Generate for specific targets
		for target := range s.Impls {
			switch target {
			case "pgimpl":
				g.generatePgMethods(s)
			}
		}
	}

	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return fmt.Errorf("failed to format generated code: %w", err)
	}

	outFile := strings.TrimSuffix(originalFile, ".go") + "_gen.go"
	return os.WriteFile(outFile, formatted, 0644)
}

func (g *generator) printf(format string, args ...interface{}) {
	fmt.Fprintf(g.buf, format, args...)
}

func (g *generator) generateImports() {
	hasDelegate := false
	imports := make(map[string]string) // alias -> path

	for _, s := range g.structs {
		for _, f := range s.Fields {
			if f.IsDelegate {
				hasDelegate = true
				if f.DelegateImportPath != "" {
					parts := strings.Split(f.TypeName, ".")
					if len(parts) > 1 {
						imports[parts[0]] = f.DelegateImportPath
					}
				}
			}
		}
	}

	if hasDelegate {
		g.printf("import (\n")
		g.printf("\t\"strings\"\n")
		for alias, path := range imports {
			g.printf("\t%s \"%s\"\n", alias, path)
		}
		g.printf(")\n\n")
	}
}

func (g *generator) generateCommonMethods(s structInfo) {
	// Check if any impl requires Entity
	var isEntity bool
	for _, set := range s.Impls {
		if set.IsEntity {
			isEntity = true
			break
		}
	}

	if isEntity {
		g.generateSortPtr(s)
		g.generateFilterPtr(s)
	}
}

func (g *generator) generateSortPtr(s structInfo) {
	g.printf("func (e %s) SortPtr(field string) any {\n", s.Name)
	g.printf("\tswitch field {\n")
	for _, f := range s.Fields {
		if f.IsDelegate {
			g.printf("\tdefault:\n")
			g.printf("\t\tif strings.HasPrefix(field, \"%s\") {\n", f.Prefix)
			g.printf("\t\t\treturn e.%s.SortPtr(strings.TrimPrefix(field, \"%s\"))\n", f.Name, f.Prefix)
			g.printf("\t\t}\n")
			continue
		}

		if f.Sort {
			g.printf("\tcase \"%s\":\n", f.FieldName)
			g.printf("\t\treturn &e.%s\n", f.Name)
		}
	}
	g.printf("\t}\n\treturn nil\n}\n\n")
}

